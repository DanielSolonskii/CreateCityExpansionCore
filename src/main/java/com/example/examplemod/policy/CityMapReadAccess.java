package com.example.examplemod.policy;

/**
 * Право открыть карту города по клавише — только чтение.
 *
 * <p><b>Почему это решение принимается здесь.</b> Карта по клавише не привязана
 * к пилону, поэтому у неё нет «доказуемого» контекста вроде открытого контейнера
 * или проверки расстояния. Единственное, что по-настоящему отличает
 * участника города от постороннего, — это членство в городе. Всё остальное
 * (открыт ли пилон, близко ли игрок) для карты не имеет значения и было бы
 * проверкой постороннего признака.
 *
 * <p><b>Почему решение — это факты, а не серверные объекты.</b> Тот же вопрос
 * «имеет ли право» решается в трёх местах, и разойтись они не должны. Здесь
 * лежит чистая функция от фактов, которую можно проверить headless; серверный
 * код только собирает факты и выполняет решение.
 *
 * <p><b>Отказ не различает причины.</b> Игрок без города и игрок, который не
 * является его участником, получают один и тот же отказ. Сообщать «у тебя нет
 * города» постороннему нельзя — это перечисление городов сервера тем, кто
 * участником не является.
 */
public final class CityMapReadAccess {

    /** Открыть карту города по клавише. */
    public enum Decision {
        /** Город есть, игрок в нём участник: карта доступна только для чтения. */
        READ_ONLY,
        /** Нет своего города, либо игрок в него не входит. */
        REFUSED
    }

    /** Входные факты. Ровно то, что сервер знает о игроке, и ничего больше. */
    public record Facts(boolean hasCity, boolean member) {
    }

    private CityMapReadAccess() {
    }

    /**
     * Решает по фактам.
     *
     * <p>Членство проверяется при любом городе: город без участника — это ровно
     * тот случай, в котором раньше уезжали данные, поэтому «город существует»
     * недостаточно для доступа.
     */
    public static Decision evaluate(Facts facts) {
        if (facts == null) {
            return Decision.REFUSED;
        }
        return facts.hasCity() && facts.member() ? Decision.READ_ONLY : Decision.REFUSED;
    }

    /** Удобная форма для вызывающего кода. */
    public static boolean allowed(Facts facts) {
        return evaluate(facts) == Decision.READ_ONLY;
    }
}