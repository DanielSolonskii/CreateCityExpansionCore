package com.example.examplemod.city;

/**
 * Исход переключения гранта пульта по блоку физической конструкции
 * (sublevel'ы Create Simulated / Aeronautics).
 *
 * <p>Перечисление живёт отдельно от {@code TransportSubLevelProtection},
 * потому что тот класс трогает типы Sable: из него нельзя
 * ссылаться из всегда-загружаемого кода — предмет-пульт общается
 * только через {@code SimulatedCompat}.
 */
public enum TransportGrantStatus {

    /** Блок не принадлежит физической конструкции: caller уходит на статический путь участков. */
    NOT_PHYSICAL,

    /** Конструкция есть, но зарегистрированного терминала города в ней нет. */
    UNREGISTERED,

    /** Переключить грант может только участник города конструкции. */
    NOT_MEMBER,

    /** Грант открыт: блок принимает взаимодействие от любого игрока. */
    GRANTED,

    /** Грант снят: блок снова охраняется общими правами. */
    REVOKED
}
